let currentLanguage = 'en';

function setLanguage(lang) {
  currentLanguage = lang === 'fa' ? 'fa' : 'en';
}

function getLanguage() {
  return currentLanguage;
}

function t(key, values = {}) {
  const table = translations[currentLanguage] || translations.en;
  let text = table[key] || translations.en[key] || key;
  if (values && typeof values === 'object') {
    for (const [k, v] of Object.entries(values)) {
      text = text.replaceAll(`{${k}}`, String(v ?? ''));
    }
  }
  return text;
}

function applyLanguage(lang) {
  if (lang) setLanguage(lang);
  const isRtl = currentLanguage === 'fa';
  document.documentElement.lang = currentLanguage;
  document.documentElement.dir = isRtl ? 'rtl' : 'ltr';

  // Toggle button label
  const langToggle = document.getElementById('lang-toggle');
  if (langToggle) {
    langToggle.textContent = isRtl ? 'English' : 'فارسی';
  }

  // Update data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    el.textContent = t(key);
  });

  // Update data-i18n-title elements
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle;
    el.title = t(key);
  });

  // Update data-i18n-aria-label elements
  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    const key = el.dataset.i18nAriaLabel;
    el.setAttribute('aria-label', t(key));
  });

  // Update data-i18n-placeholder elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    el.placeholder = t(key);
  });
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { translations, t, setLanguage, getLanguage, applyLanguage };
} else {
  window.i18n = { translations, t, setLanguage, getLanguage, applyLanguage };
}
